/**
 * Colab pull-worker notebook generator.
 *
 * Google Colab has no public execution API, so the honest "background Colab"
 * path is: this service generates a ready-to-run notebook, pre-configured
 * for one of Jay's Supabase job queues. Open it in Colab, Run-all, leave the
 * tab open — the loop pulls queued jobs, runs them on the free GPU, uploads
 * results to his own Supabase Storage, and marks jobs done.
 *
 * Queue shapes reused verbatim:
 *  - train: train_jobs {id, model_repo, dataset, lora_rank, status,
 *           result_url, metrics_json, error}  (train-studio)
 *  - asset: forge_asset_jobs {id, prompt, image_url, status, result_url,
 *           module_url, error}                (gameforge-mcp)
 */

export type WorkerType = "train" | "asset";

interface NbCell {
  cell_type: "markdown" | "code";
  metadata: Record<string, unknown>;
  source: string[];
  execution_count?: null;
  outputs?: unknown[];
}

function md(lines: string[]): NbCell {
  return {
    cell_type: "markdown",
    metadata: {},
    source: lines.map((l) => l + "\n"),
  };
}

function code(lines: string[]): NbCell {
  return {
    cell_type: "code",
    metadata: {},
    execution_count: null,
    outputs: [],
    source: lines.map((l) => l + "\n"),
  };
}

function shell(lines: string[]): NbCell {
  return code(lines.map((l) => (l.startsWith("!") || l.startsWith("%") ? l : "!" + l)));
}

export function workerNotebook(
  type: WorkerType,
  opts: { supabaseUrl?: string; supabaseKey?: string } = {},
): Record<string, unknown> {
  const table = type === "train" ? "train_jobs" : "forge_asset_jobs";
  const bucket = type === "train" ? "train-adapters" : "forge-assets";
  const url = opts.supabaseUrl || "PASTE_SUPABASE_URL";
  const key = opts.supabaseKey || "PASTE_SERVICE_ROLE_KEY";

  const cells: NbCell[] = [
    md([
      `# GPU Pull Worker — ${type === "train" ? "Train Studio (QLoRA)" : "Forge Assets (3D)"}`,
      "",
      "Generated by **kaggle-colab-runner**. Runs **in this notebook** on a free",
      "Colab GPU, but driven by the app queue: it pulls jobs from Supabase",
      `\`${table}\`, runs them, uploads results to **your own** Supabase Storage`,
      `bucket \`${bucket}\`, marks jobs done, then wipes the local job dir.`,
      "",
      "Leave the tab open — the loop polls every 30s. Restarting loses nothing.",
    ]),
    code([
      "import os",
      `SUPABASE_URL = os.environ.get("SUPABASE_URL", ${JSON.stringify(url)})`,
      `SUPABASE_KEY = os.environ.get("SUPABASE_KEY", ${JSON.stringify(key)})`,
      `TABLE = ${JSON.stringify(table)}`,
      `BUCKET = ${JSON.stringify(bucket)}`,
      'assert "PASTE_" not in SUPABASE_URL, "set SUPABASE_URL first"',
      'assert "PASTE_" not in SUPABASE_KEY, "set SUPABASE_KEY (service_role) first"',
      'print("queue:", TABLE, "->", SUPABASE_URL)',
    ]),
    code([
      "import torch",
      'print("cuda:", torch.cuda.is_available(), torch.cuda.get_device_name(0) if torch.cuda.is_available() else "NONE - use Runtime > Change runtime type > GPU")',
    ]),
  ];

  if (type === "train") {
    cells.push(
      shell([
        "pip -q install unsloth",
        "pip -q install --no-deps xformers trl peft accelerate bitsandbytes datasets",
      ]),
      code(TRAIN_WORKER.split("\n")),
    );
  } else {
    cells.push(
      shell([
        "pip -q install diffusers transformers accelerate safetensors trimesh pillow",
        "pip -q install git+https://github.com/VAST-AI-Research/TripoSR.git",
      ]),
      code(ASSET_WORKER.split("\n")),
    );
  }

  return {
    nbformat: 4,
    nbformat_minor: 5,
    metadata: {
      kernelspec: { display_name: "Python 3", language: "python", name: "python3" },
      language_info: { name: "python", version: "3.10.0" },
      colab: { provenance: [{ file_id: "kaggle-colab-runner", timestamp: Date.now() }] },
    },
    cells,
  };
}

const REST_HELPERS = `
import json, time, shutil, urllib.request, urllib.parse
from pathlib import Path

def _req(method, path, body=None):
    req = urllib.request.Request(
        SUPABASE_URL + path, method=method,
        headers={"apikey": SUPABASE_KEY, "Authorization": f"Bearer {SUPABASE_KEY}",
                 "Content-Type": "application/json", "Prefer": "return=representation"})
    data = json.dumps(body).encode() if body is not None else None
    with urllib.request.urlopen(req, data=data, timeout=60) as r:
        t = r.read().decode()
        return json.loads(t) if t.strip() else []

def claim_job():
    # atomic-ish: oldest queued -> working (first claimer wins on low contention)
    rows = _req("GET", f"/rest/v1/{TABLE}?status=eq.queued&order=created_at.asc&limit=1&select=*")
    if not rows: return None
    jid = rows[0]["id"]
    upd = _req("PATCH", f"/rest/v1/{TABLE}?id=eq.{jid}", {"status": "working"})
    return upd[0] if upd else None

def finish_job(jid, ok, result_url="", extra=None, error=""):
    body = {"status": "done" if ok else "failed", "result_url": result_url or None,
            "error": (error or "")[:2000] or None}
    if extra: body.update(extra)
    _req("PATCH", f"/rest/v1/{TABLE}?id=eq.{jid}", body)

def upload_file(local: Path, dest: str):
    data = local.read_bytes()
    req = urllib.request.Request(
        f"{SUPABASE_URL}/storage/v1/object/{BUCKET}/{dest}", method="POST",
        headers={"apikey": SUPABASE_KEY, "Authorization": f"Bearer {SUPABASE_KEY}",
                 "Content-Type": "application/octet-stream", "x-upsert": "true"},
        data=data)
    with urllib.request.urlopen(req, timeout=300) as r: r.read()
    return f"{SUPABASE_URL}/storage/v1/object/public/{BUCKET}/{dest}"

def wipe(d: Path):
    shutil.rmtree(d, ignore_errors=True)
    try:
        import torch
        if torch.cuda.is_available(): torch.cuda.empty_cache()
    except Exception: pass
`;

const TRAIN_WORKER =
  REST_HELPERS +
  `
def train_one(job):
    jid = job["id"]; work = Path(f"/tmp/ts-{jid[:8]}"); work.mkdir(exist_ok=True)
    try:
        from unsloth import FastLanguageModel
        import torch
        model, tok = FastLanguageModel.from_pretrained(
            model_name=job["model_repo"], max_seq_length=2048,
            dtype=None, load_in_4bit=True)
        model = FastLanguageModel.get_peft_model(
            model, r=int(job.get("lora_rank") or 16), lora_alpha=32,
            lora_dropout=0, bias="none", use_gradient_checkpointing="unsloth")
        # tiny demo dataset (alpaca-style); swap for job["dataset"] as needed
        from datasets import Dataset
        ds = Dataset.from_list([
            {"text": "### Instruction: Say hi.\\n### Response: Hello from the GPU worker!"}] * 32)
        def fmt(b):
            return {"text": [tok.apply_chat_template(
                [{"role": "user", "content": t}], tokenize=False) for t in b["text"]]}
        from trl import SFTTrainer
        from transformers import TrainingArguments
        tr = SFTTrainer(model=model, tokenizer=tok, train_dataset=ds.map(fmt, batched=True),
            dataset_text_field="text", max_seq_length=2048,
            args=TrainingArguments(per_device_train_batch_size=2,
                gradient_accumulation_steps=4, max_steps=60, logging_steps=10,
                output_dir=str(work), optim="adamw_8bit", seed=3407))
        tr.train()
        model.save_pretrained(str(work / "adapter")); tok.save_pretrained(str(work / "adapter"))
        # zip adapter dir -> single upload
        import zipfile
        zpath = work / "adapter.zip"
        with zipfile.ZipFile(zpath, "w", zipfile.ZIP_DEFLATED) as z:
            for p in (work / "adapter").rglob("*"):
                if p.is_file(): z.write(p, p.relative_to(work / "adapter"))
        url = upload_file(zpath, f"{jid}/adapter.zip")
        loss = float(tr.state.log_history[-1].get("loss", 0)) if tr.state.log_history else 0
        finish_job(jid, True, url, {"metrics_json": {"loss": loss, "steps": 60}})
        print("done", jid, url)
    except Exception as e:
        import traceback; traceback.print_exc()
        finish_job(jid, False, error=str(e)[:2000])
        print("failed", jid, e)
    finally:
        wipe(work)

print("worker ready — polling", TABLE)
while True:
    job = claim_job()
    if job:
        print("claimed", job["id"], job.get("model_repo"))
        train_one(job)
    else:
        time.sleep(30)
`;

const ASSET_WORKER =
  REST_HELPERS +
  `
def asset_one(job):
    jid = job["id"]; work = Path(f"/tmp/fa-{jid[:8]}"); work.mkdir(exist_ok=True)
    try:
        import torch
        from diffusers import AutoPipelineForText2Image
        pipe = AutoPipelineForText2Image.from_pretrained(
            "stabilityai/sdxl-turbo", torch_dtype=torch.float16, variant="fp16")
        pipe.to("cuda"); pipe.enable_attention_slicing()
        img = pipe(prompt=job["prompt"], num_inference_steps=4, guidance_scale=0.0).images[0]
        img_path = work / "ref.png"; img.save(img_path)
        # image -> 3D with TripoSR
        from tsr.system import TSR
        from tsr.utils import remove_background, resize_foreground, to_gradio_3d_orthographic
        import numpy as np, trimesh
        from PIL import Image
        model = TSR.from_pretrained("stabilityai/TripoSR", config_name="config.yaml", weight_name="model.ckpt")
        model.to("cuda")
        image = Image.open(img_path).convert("RGB")
        image = remove_background(image); image = resize_foreground(image, 0.85)
        image = np.array(image).astype(np.float32) / 255.0
        image = image[:, :, ::-1].copy(); image = to_gradio_3d_orthographic(image)
        with torch.no_grad():
            scene_codes = model([torch.FloatTensor(image).to("cuda")], device="cuda")
        mesh = model.extract_mesh(scene_codes, has_vertex_color=True)[0]
        glb_path = work / "model.glb"; mesh.export(glb_path)
        url = upload_file(glb_path, f"{jid}/model.glb")
        finish_job(jid, True, url)
        print("done", jid, url)
    except Exception as e:
        import traceback; traceback.print_exc()
        finish_job(jid, False, error=str(e)[:2000])
        print("failed", jid, e)
    finally:
        wipe(work)

print("worker ready — polling", TABLE)
while True:
    job = claim_job()
    if job:
        print("claimed", job["id"], (job.get("prompt") or "")[:60])
        asset_one(job)
    else:
        time.sleep(30)
`;
